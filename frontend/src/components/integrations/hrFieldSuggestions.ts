/** The HR field name the document uses for this AttendHub field of this purpose, if it names one. */
export function suggestedHrField(purposeName: string | undefined, attendHubField: string): string | undefined {
  if (!purposeName) return undefined;
  return SUGGESTIONS[purposeName]?.[attendHubField];
}

/** Every HR field name the document lists for a purpose (for the suggestion list). */
export function suggestedHrFields(purposeName: string | undefined): string[] {
  if (!purposeName) return [];
  return Array.from(new Set(Object.values(SUGGESTIONS[purposeName] ?? {})));
}
